#!/usr/bin/env python3
"""Collect Ekos Notifier's translatable messages into src/ekos_notifier/locale/ekos-notifier.pot.

Finds every ``_("…")``, ``N_("…")`` and ``ngettext("…", "…", n)`` with literal strings in the
package source, and writes the gettext template translators start from. Run it after changing
a message; a test fails while the template is out of date. Then bring the translations up to
date (``msgmerge --update locale/de.po locale/ekos-notifier.pot``, or Poedit's "Update from POT
file"). Stdlib only.

Usage: python tools/update_pot.py [--check]

--check also checks every translation in locale/: its placeholders must match the English.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "ekos_notifier"
POT = PACKAGE / "locale" / "ekos-notifier.pot"
FUNCTIONS = {"_": 1, "N_": 1, "ngettext": 2}
BRACE = re.compile(r"\{[A-Za-z_]\w*(?:[:!][^{}]*)?\}")

HEADER = """\
# Ekos Notifier's messages, for translators.
# Generated by tools/update_pot.py: don't edit by hand.
# A translation is locale/<language>.po (de.po, pt_BR.po); see CONTRIBUTING.md.
msgid ""
msgstr ""
"Project-Id-Version: ekos-notifier\\n"
"Report-Msgid-Bugs-To: https://github.com/anandvn/ekos-notifier/issues\\n"
"PO-Revision-Date: YEAR-MO-DA HO:MI+ZONE\\n"
"Last-Translator: FULL NAME <EMAIL@ADDRESS>\\n"
"Language-Team: LANGUAGE <LL@li.org>\\n"
"Language: \\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\\n"
"""


def extract(package: Path = PACKAGE) -> dict[tuple[str, str | None], list[str]]:
    """{(msgid, msgid_plural or None): [files using it]}, in source order. Files only, not line
    numbers, so the template changes only when a message does."""
    found: dict[tuple[str, str | None], list[str]] = {}
    for path in sorted(package.rglob("*.py")):
        rel = path.relative_to(package.parent).as_posix()
        tree = ast.parse(path.read_text(encoding="utf-8"), str(path))
        calls = sorted(
            (n for n in ast.walk(tree) if isinstance(n, ast.Call)),
            key=lambda n: (n.lineno, n.col_offset),
        )
        for node in calls:
            if not isinstance(node.func, ast.Name):
                continue
            count = FUNCTIONS.get(node.func.id)
            if count is None or len(node.args) < count:
                continue
            args = node.args[:count]
            if not all(isinstance(a, ast.Constant) and isinstance(a.value, str) for a in args):
                continue
            strings = [a.value for a in args]  # type: ignore[attr-defined]
            key = (strings[0], strings[1] if count == 2 else None)
            where = found.setdefault(key, [])
            if rel not in where:
                where.append(rel)
    return found


def quote(text: str) -> str:
    """A .po string, split after newlines the way gettext tools write them."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
    lines = escaped.split("\n")
    parts = [line + "\\n" for line in lines[:-1]] + ([lines[-1]] if lines[-1] else [])
    if len(parts) <= 1:
        return f'"{parts[0] if parts else ""}"'
    return '""\n' + "\n".join(f'"{p}"' for p in parts)


def pot(found: dict[tuple[str, str | None], list[str]]) -> str:
    out = [HEADER.rstrip("\n")]
    for (msgid, plural), where in found.items():
        out.append("")
        out.append("#: " + " ".join(where))
        if BRACE.search(msgid) or (plural and BRACE.search(plural)):
            out.append("#, python-brace-format")
        out.append(f"msgid {quote(msgid)}")
        if plural is None:
            out.append('msgstr ""')
        else:
            out.append(f"msgid_plural {quote(plural)}")
            out.append('msgstr[0] ""')
            out.append('msgstr[1] ""')
    return "\n".join(out) + "\n"


def placeholders(text: str) -> set[str]:
    return {re.split(r"[:!]", m.group(0)[1:-1])[0] for m in BRACE.finditer(text)}


def problems(po: Path, found: dict[tuple[str, str | None], list[str]] | None = None) -> list[str]:
    """What's wrong in a translation: placeholders that don't match the English (a translation
    uses exactly the same {names}, in any order; a plural form may leave out {n}), and
    translations of messages the code no longer has."""
    sys.path.insert(0, str(PACKAGE.parent))
    from ekos_notifier.i18n import parse_po

    found = extract() if found is None else found
    plurals = {msgid: plural for msgid, plural in found if plural}
    known = {msgid for msgid, _plural in found}
    try:
        catalog = parse_po(po.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [f"{po.name}: can't be read: {exc}"]
    out = []
    for key, translated in catalog.items():
        msgid = key[0] if isinstance(key, tuple) else key
        if not msgid:
            continue  # the header
        if msgid not in known:
            out.append(f"{po.name}: {msgid!r} isn't a message any more (msgmerge drops it)")
            continue
        english = placeholders(msgid) | placeholders(plurals.get(msgid, ""))
        have = placeholders(translated)
        if have == english or (isinstance(key, tuple) and have == english - {"n"}):
            continue
        out.append(
            f"{po.name}: {msgid!r} -> {translated!r}: uses {sorted(have)}, the English"
            f" {sorted(english)}"
        )
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if the template is out of date or a translation's placeholders are wrong",
    )
    args = ap.parse_args()
    found = extract()
    text = pot(found)
    if args.check:
        current = POT.read_text(encoding="utf-8") if POT.exists() else ""
        errors = []
        if current != text:
            errors.append(f"{POT.relative_to(ROOT)} is out of date: run tools/update_pot.py")
        for po in sorted(POT.parent.glob("*.po")):
            errors += problems(po, found)
        for error in errors:
            print(error, file=sys.stderr)
        return 1 if errors else 0
    POT.parent.mkdir(parents=True, exist_ok=True)
    POT.write_text(text, encoding="utf-8")
    print(f"{POT.relative_to(ROOT)}: {len(found)} messages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
